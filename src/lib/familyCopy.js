function stemLine(chart) {
  const stem = chart?.dayMasterKo;
  if (stem && LIFE_BY_STEM[stem]) return LIFE_BY_STEM[stem];
  return "내 중심 기운 정보가 충분하지 않아 일반적인 참고로만 말씀드립니다. 가족과의 약속은 짧게라도 미리 말해 두면 마음이 편해집니다.";
}

function yongLine(chart) {
  const yong = chart?.strength?.favorable?.[0];
  if (yong && LIFE_BY_YONG[yong]) return LIFE_BY_YONG[yong];
  return "도움이 되는 기운 값이 뚜렷하지 않습니다. 이럴 때는 큰 결정보다, 이번 주 함께할 시간 한 칸만 달력에 비워 두세요.";
}

function monthLine(chart) {
  const monthGod = chart?.monthGod;
  if (monthGod && LIFE_MONTH_GOD[monthGod]) return LIFE_MONTH_GOD[monthGod];
  return "월주 태도 값이 뚜렷하지 않으면, 가족 앞 말투만 한 톤 낮춰도 분위기가 한결 풀리는 경우가 많습니다.";
}

function decadeLine(guide) {
  const decades = (guide?.decades || []).filter((c) => c?.gzKo && c.gzKo !== "대운 전" && c.startYear && c.endYear);
  const focus = decades.find((c) => typeof c.score === "number" && c.score >= 68) || decades[0];
  if (focus) {
    const level = focus.level ? `(${focus.level})` : "";
    return `큰 흐름(대략 10년)으로 ${focus.startYear}–${focus.endYear}년 ${focus.gzKo}${level} 구간이 자료에 있습니다. 이 시기에도 관계를 단정하지 말고, 대화·일정·휴식을 먼저 맞춰 보시면 됩니다.`;
  }
  return "지금은 대운 구간 자료가 충분하지 않습니다. 추측하기보다, 이번 달 가족(또는 가까운 사람)과 나눌 일정 하나만 적어 두세요.";
}

