function decorate(hanja, gloss) {
  const meta = hanjaMeta(hanja);
  return {
    h: hanja,
    gloss,
    stroke: meta.stroke,
    element: meta.element,
    pole: meta.pole,
    label: meta.stroke
      ? `${hanja} ${gloss} · ${meta.stroke}획 · ${meta.element}`
      : `${hanja} ${gloss}`,
  };
}

function choices(rows) {
  const seen = new Set();
  return (rows || [])
    .filter((row) => {
      const h = row?.[0];
      if (!h || row[1] === "" || seen.has(h)) return false;
      seen.add(h);
      return true;
    })
    .map(([h, gloss]) => decorate(h, gloss));
}

export function hangulOnly(value) {
  return [...String(value || "")].filter((ch) => /[가-힣]/.test(ch)).join("");
}

export function surnameChoices(surname) {
  const name = hangulOnly(surname);
  const compound = COMPOUNDS.find((item) => name.startsWith(item));
  return choices(SURNAMES[compound || name]);
}

export function givenChoices(given) {
  return [...hangulOnly(given)].map((syllable) => ({
    syllable,
    choices: choices(SYLLABLES[syllable]),
  }));
}

export function preferredSurname(surname) {
  return surnameChoices(surname)[0]?.h || "";
}

export function preferredGiven(given) {
  const items = givenChoices(given);
  if (items.length === 0 || items.some((item) => item.choices.length === 0)) return "";
  return items.map((item) => item.choices[0].h).join("");
}

export function replaceGivenSyllable(current, index, hanja, length) {
  const chars = [...String(current || "")];
  while (chars.length < length) chars.push("");
  chars[index] = hanja;
  return chars.slice(0, length).join("");
}
