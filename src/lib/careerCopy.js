export function buildCareerLifePlain(chart, guide, nature) {
  const lines = [];
  const stem = chart?.dayMasterKo;
  const yong = chart?.strength?.favorable?.[0];
  const monthGod = chart?.monthGod;
  const gods = (chart?.pillars || []).map((p) => p.shiShen).filter(Boolean);
  const officerHit = ["정관", "편관"].filter((g) => gods.includes(g));
  const resourceHit = ["정인", "편인"].filter((g) => gods.includes(g));

  if (stem && LIFE_BY_STEM[stem]) lines.push(LIFE_BY_STEM[stem]);
  else {
    lines.push(
      "내 중심 기운 정보가 충분하지 않아 일반적인 참고로만 말씀드립니다. 맡은 일과 마감을 한 줄로 적어 두는 습관부터 두시면 됩니다.",
    );
  }

  if (nature?.fit || nature?.trait) {
    const parts = [];
    if (nature.trait) parts.push(nature.trait);
    if (nature.fit) parts.push(`잘 맞는 일의 결은 ${nature.fit} 쪽입니다.`);
    lines.push(
      `직장에서의 강점: ${parts.join(" ")} 다만 이 안내가 특정 직업의 성공이나 취업을 보장하지는 않습니다.`,
    );
  } else {
    lines.push(
      "직업 성향 자료가 충분하지 않습니다. 추측하지 않고, 지금 맡은 일에서 ‘끝까지 마감한 일’ 하나만 기록해 보세요.",
    );
  }

  if (nature?.slip) {
    lines.push(`주의할 점: ${nature.slip}입니다. 짧게 메모로 보완하면 실수가 눈에 띄게 줄어듭니다.`);
  } else if (monthGod && LIFE_MONTH_GOD[monthGod]) {
    lines.push(LIFE_MONTH_GOD[monthGod]);
  } else {
    lines.push(
      "월주 태도 값이 뚜렷하지 않으면, 상사·동료에게 보이는 말투만 한 톤 낮춰도 관계가 편해지는 경우가 많습니다.",
    );
  }

  if (yong && LIFE_BY_YONG[yong]) lines.push(LIFE_BY_YONG[yong]);
  else {
    lines.push(
      "도움이 되는 기운 값이 뚜렷하지 않습니다. 이럴 때는 새 일보다 이번 주 마감 하나부터 정리하시는 편이 안전합니다.",
    );
  }

  if (officerHit.length) {
    officerHit.forEach((g) => {
      if (LIFE_OFFICER[g]) lines.push(LIFE_OFFICER[g]);
    });
  } else if (resourceHit.length) {
    resourceHit.forEach((g) => {
      if (LIFE_RESOURCE[g]) lines.push(LIFE_RESOURCE[g]);
    });
  } else {
    lines.push(
      "자리·책임이나 배움 관련 글자가 원국에서 뚜렷하지 않습니다. 무리해 해석하지 말고, 맡은 범위를 문장으로만 적어 두세요.",
    );
  }

  const decades = (guide?.decades || []).filter((c) => c?.gzKo && c.gzKo !== "대운 전" && c.startYear && c.endYear);
  const focus = decades.find((c) => typeof c.score === "number" && c.score >= 70) || decades[0];
  if (focus) {
    const level = focus.level ? `(${focus.level})` : "";
    lines.push(
      `큰 흐름(대략 10년)으로 ${focus.startYear}–${focus.endYear}년 ${focus.gzKo}${level} 구간이 자료에 있습니다. 이 시기에도 승진·이직을 단정하지 말고, 기록·수면·역할 분담부터 챙기시면 됩니다.`,
    );
  } else {
    lines.push(
      "지금은 대운 구간 자료가 충분하지 않습니다. 대운을 추측하기보다, 이번 달 할 일 목록만 먼저 정리해 두세요.",
    );
  }

  // 지금 실천할 일 한 가지
  if (nature?.slip) {
    lines.push(`지금 실천할 일 한 가지: ‘${nature.slip}’이 나오기 쉬운 날에는, 중요한 메일·보고를 보내기 전 한 번만 다시 읽어 보세요.`);
  } else if (yong === "금") {
    lines.push("지금 실천할 일 한 가지: 이번 주 마감 일정을 달력에 한 줄로만 적어 두세요.");
  } else if (yong === "화") {
    lines.push("지금 실천할 일 한 가지: 사람 만난 날에는 다음 할 일 하나만 메모로 남기세요.");
  } else if (yong === "목") {
    lines.push("지금 실천할 일 한 가지: 새 제안은 주 1개만 실행하고, 나머지는 대기열에 두세요.");
  } else if (yong === "토") {
    lines.push("지금 실천할 일 한 가지: 맡은 업무 범위를 세 줄 이내로 적어 동료와 맞춰 보세요.");
  } else if (yong === "수") {
    lines.push("지금 실천할 일 한 가지: 급한 회신은 하루를 자고 보내 보세요.");
  } else {
    lines.push("지금 실천할 일 한 가지: 이번 주 꼭 마칠 일 하나만 골라 달력에 적어 두세요.");
  }

  lines.push("이 안내는 직장 생활 습관을 돕는 참고이며, 특정 직업의 성공·취업·승진을 약속하지 않습니다.");

  return {
    title: "생활 속 직업운 풀이",
    lines: lines.filter(Boolean),
  };
}
