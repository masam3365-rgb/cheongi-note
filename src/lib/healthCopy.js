function describeCount(count) {
  if (!count || typeof count !== "object") return "";
  const entries = ["목", "화", "토", "금", "수"]
    .map((el) => [el, Number(count[el]) || 0])
    .filter(([, n]) => n > 0)
    .sort((a, b) => b[1] - a[1]);
  if (!entries.length) return "";
  const [topEl, topN] = entries[0];
  const [lowEl, lowN] = entries[entries.length - 1];
  if (topEl === lowEl) {
    return `오행 분포를 보면 ${topEl} 쪽이 상대적으로 눈에 띕니다. 이는 생활 리듬의 참고일 뿐, 특정 질환을 뜻하지 않습니다.`;
  }
  return `오행 분포를 보면 ${topEl} 쪽(${topN})이 상대적으로 많고, ${lowEl} 쪽(${lowN})은 적은 편입니다. 많고 적음은 페이스 조절의 힌트일 뿐, 병명과 바로 이어지지 않습니다.`;
}

export function buildHealthLifePlain(chart, guide) {
  const lines = [];
  const stem = chart?.dayMasterKo;
  const label = chart?.strength?.label;
  const yong = chart?.strength?.favorable?.[0];
  const unfav = chart?.strength?.unfavorable?.[0];
  const habit = guide?.table?.habit;

  if (stem && LIFE_BY_STEM[stem]) lines.push(LIFE_BY_STEM[stem]);
  else {
    lines.push(
      "내 중심 기운 정보가 충분하지 않아 일반적인 참고로만 말씀드립니다. 수면과 식사 시각을 지키는 것부터 시작해 보시면 됩니다.",
    );
  }

  if (label === "신강" || label === "신약") {
    lines.push(
      label === "신강"
        ? "지금의 체질 온도는 ‘힘이 센 편’으로 읽힙니다. 밀어붙이기보다 쉬는 날을 달력에 적어 두면 컨디션이 오래갑니다."
        : "지금의 체질 온도는 ‘채움이 필요한 편’으로 읽힙니다. 무리한 일정 전에 식사·수면부터 채우면 몸이 한결 편해지기 쉽습니다.",
    );
  }

  const countLine = describeCount(chart?.count);
  if (countLine) lines.push(countLine);

  // 생활관리 2~3문장: 수면·휴식·식사·가벼운 운동·스트레스 중 관련 있는 것
  const tips = [];
  if (yong && LIFE_BY_YONG[yong]) tips.push(LIFE_BY_YONG[yong]);
  if (unfav && PACE_BY_UNFAV[unfav]) tips.push(PACE_BY_UNFAV[unfav]);
  if (habit) tips.push(String(habit));
  if (!tips.length) {
    tips.push(
      "수면·휴식·식사만 규칙적으로 맞춰도 하루 리듬이 한결 안정되는 경우가 많습니다. 스트레스가 클 때는 일정을 하나 줄이는 것이 가장 빠른 회복입니다.",
    );
  }
  lines.push(...tips.slice(0, 3));

  if (yong && ACTION_BY_YONG[yong]) lines.push(ACTION_BY_YONG[yong]);
  else lines.push("지금 실천할 일 한 가지: 오늘 취침 시각만 미리 정해 알람을 맞춰 두세요.");

  lines.push(
    "이 안내는 일반적인 생활관리 참고용이며, 사주만으로 질병·장기 이상·발병 시기·수명을 진단하거나 예측하지 않습니다. 몸이나 마음에 증상이 있으면 의료 전문가와 상담하시기 바랍니다.",
  );

  return {
    title: "생활 속 건강운 풀이",
    lines: lines.filter(Boolean),
  };
}
