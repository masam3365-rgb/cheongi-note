export function buildWealthEastern(chart) {
  const stem = chart.dayMasterKo || "무";
  const strong = Boolean(chart.strength?.strong);
  const fav = chart.strength?.favorable || [];
  const unfav = chart.strength?.unfavorable || [];
  const yong = fav[0] || "토";
  const gods = (chart.pillars || []).map((p) => p.shiShen).filter(Boolean);
  const hasZheng = gods.includes("정재");
  const hasPian = gods.includes("편재");
  const seed = `${stem}${yong}${strong ? "S" : "W"}${gods.join("")}`;

  const roleLine = hasZheng && hasPian
    ? "성실히 쌓는 수입과 기회성 수입이 함께 보입니다. 고정 수입과 프로젝트 수입의 장부를 나누면 리스크가 줄습니다."
    : hasZheng
      ? "성실히 쌓는 재물 감각이 또렷합니다. 정기 입금·세금·저축 일정을 한 달력에 두세요."
      : hasPian
        ? "기회·유통성 수입이 잘 붙는 편입니다. 들어오면 바로 쓰기보다 수수료·세금·예비를 먼저 떼세요."
        : "재물은 생활의 숫자로 드러납니다. 수입·지출·계약·저축 네 칸만 나눠도 구멍이 보입니다.";

  return [
    hashPick(seed, STEM_OPENERS[stem] || STEM_OPENERS.무),
    hashPick(`${seed}-st`, strong ? STRONG_LINES : WEAK_LINES),
    roleLine,
    hashPick(`${seed}-y`, YONG_FOCUS[yong] || YONG_FOCUS.토),
    `과하면 부담이 되기 쉬운 결은 ${elementPhrase(unfav[0] || "—", "wealth")} 쪽입니다. 그 기운이 센 날에는 큰 계약·당일 송금을 하루 미루세요.`,
  ];
}

