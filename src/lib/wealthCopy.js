function hashPick(seed, list) {
  const arr = list.filter(Boolean);
  if (!arr.length) return "";
  let h = 0;
  const s = String(seed || "");
  for (let i = 0; i < s.length; i += 1) h = (h * 33 + s.charCodeAt(i)) >>> 0;
  return arr[h % arr.length];
}

